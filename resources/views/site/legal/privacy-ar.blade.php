<h2>٢. كيف نستخدم بياناتك</h2>
<ul>
    <li>تشغيل حسابك ونشر إعلاناتك وعرضها وتمكين المحادثات والتقييمات.</li>
    <li>مراجعة الإعلانات قبل نشرها، والتعامل مع البلاغات، وحماية المستخدمين من الاحتيال والإساءة.</li>
    <li>إرسال الإشعارات داخل التطبيق والموقع، والإشعارات على الهاتف إن سمحت بها.</li>
    <li>إرسال رمز استعادة كلمة المرور إلى بريدك الإلكتروني عند طلبك ذلك.</li>
    <li>التحقق من مدفوعات تمييز الإعلانات.</li>
</ul>
<p>لا نبيع بياناتك، ولا نستخدمها للإعلانات الموجّهة، ولا نشاركها مع معلنين.</p>

