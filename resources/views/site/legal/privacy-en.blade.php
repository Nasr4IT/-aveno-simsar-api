<p>This policy explains how <strong>Simsar</strong> — the website <span dir="ltr">simsar-sy.com</span> and the Simsar mobile app — collects, uses and protects your personal data, and what your rights are. By using Simsar you agree to this policy.</p>

<h2>1. Data we collect</h2>
<ul>
    <li><strong>Account data:</strong> your name, phone number (used to log in), password (stored encrypted — nobody can read it), email if you add one (optional), your governorate and city if you choose them, and your profile photo if you upload one.</li>
    <li><strong>Ads:</strong> title, description, price, photos, specifications, location (governorate, city and street address if you add it), and the contact options you choose.</li>
    <li><strong>Chats:</strong> the messages you exchange with other users about ads.</li>
    <li><strong>Ratings and reports:</strong> ratings you give or receive, and reports you send about an ad or a user.</li>
    <li><strong>Payment receipts:</strong> when you ask to feature an ad, the screenshot of your Sham Cash transfer receipt, the transaction number and any note you send.</li>
    <li><strong>Technical data:</strong> IP address and browser or device type, for security (for example, blocking repeated login attempts), and your device's notification token if you allow notifications in the app.</li>
    <li><strong>Location:</strong> we do not track your location. Only when you use "Nearest to me" is your device's location sent with that one search to sort the results — it is not stored.</li>
</ul>

<h2>2. How we use your data</h2>
<ul>
    <li>To run your account, publish and show your ads, and enable chats and ratings.</li>
    <li>To review ads before they go live, handle reports, and protect users from fraud and abuse.</li>
    <li>To send in-app and website notifications, and phone notifications if you allow them.</li>
    <li>To email you a password-reset code when you ask for one.</li>
    <li>To verify payments for featured ads.</li>
</ul>
<p>We do not sell your data, use it for targeted advertising, or share it with advertisers.</p>

<h2>3. What other people can see</h2>
<ul>
    <li><strong>Publicly:</strong> your published ads, and your name, profile photo, governorate, city, rating, join date and number of ads.</li>
    <li><strong>Your phone number</strong> is not public. It appears on your ad only to logged-in users, and only if you allow calls and haven't chosen to hide your number.</li>
    <li><strong>Your email</strong> is never shown to other users.</li>
    <li><strong>Chats</strong> are visible only to the two people in them. The admin panel does not show chat contents, and we only look at them when needed to investigate fraud or abuse, or when legally required by a competent authority.</li>
    <li><strong>Payment receipts</strong> are visible only to the person who sent them and to the admin team — never through a public link.</li>
    <li><strong>Unpublished ads</strong> (pending review or rejected) are visible only to their owner and the admin team.</li>
</ul>

<h2>4. Third parties</h2>
<ul>
    <li><strong>Hosting:</strong> data is stored on servers rented from a hosting provider.</li>
    <li><strong>Phone notifications</strong> are delivered through Google's Firebase Cloud Messaging, which receives only your device token and the notification text.</li>
    <li><strong>Email:</strong> password-reset codes are sent through an email provider.</li>
    <li><strong>Payments:</strong> transfers happen inside the Sham Cash app itself; we never receive or store your Sham Cash login or card details.</li>
</ul>

<h2>5. Cookies</h2>
<p>The website uses only essential cookies: a session cookie to keep you logged in, a security cookie that protects forms from forged requests, and one that remembers your chosen language. Your dark-mode choice is stored only in your browser. We use no tracking, analytics or advertising cookies.</p>

<h2>6. How long we keep data</h2>
<ul>
    <li>We keep your account data while your account exists.</li>
    <li>A deleted ad disappears from Simsar immediately.</li>
    <li>Payment receipts and their records are kept as long as needed to verify payments and resolve any dispute.</li>
    <li>A password-reset code is valid for 30 minutes and can be used once.</li>
</ul>

<h2>7. Deleting your account, and your rights</h2>
<ul>
    <li>You can edit your details at any time on your "My account" page.</li>
    <li>You can <strong>delete your account yourself</strong> from "My account" on the website or in the app. When you do:
        <ul>
            <li>your ads, favorites and ratings are removed;</li>
            <li>your account details (name, phone, email, photo, location) are wiped;</li>
            <li>messages you sent stay in the other person's chat, shown as "Deleted user", so they don't lose their conversation history.</li>
        </ul>
    </li>
    <li>You can contact us to request a copy of your data, or to have it corrected or deleted.</li>
</ul>

<h2>8. Security</h2>
<p>We protect data with encrypted connections (HTTPS), encrypted passwords, limits on login attempts, and admin-only access to the admin panel. No system is perfectly secure, so please choose a strong password and don't share it.</p>

<h2>9. Age</h2>
<p>Simsar is intended for people aged 18 and over, and we do not knowingly collect data from anyone younger.</p>

<h2>10. Changes to this policy</h2>
<p>We may update this policy when our services change. We will publish the new version on this page with its last-updated date, and notify you on Simsar if the change is significant.</p>
